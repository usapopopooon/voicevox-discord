def _is_kana_only(s: str) -> bool:
    """文字列が空でなく、全文字がひらがな/カタカナか。"""
    return bool(s) and all(
        ("\u30a0" <= ch <= "\u30ff") or ("\u3040" <= ch <= "\u309f") for ch in s
    )


# CJK 互換漢字エリア (U+3300-U+33FF) の Squared Katakana words を NFKC 分解で
# 自動展開する。例: ㌔→キロ、㍉→ミリ、㍍→メートル、㌫→パーセント。
# Latin 表記に分解されるもの (㎐→Hz 等) は別途
# `_CJK_COMPAT_LATIN_UNIT_READINGS` で日本語カナ表記を手書き登録する
# （NFKC の "Hz" 等を TTS に渡すと engine 依存で読みが変わるため）。
_CJK_COMPAT_UNIT_READINGS: dict[str, str] = {
    chr(c): nfkc
    for c in range(0x3300, 0x3400)
    if (nfkc := unicodedata.normalize("NFKC", chr(c))) != chr(c) and _is_kana_only(nfkc)
}
READING_CORRECTIONS.update(_CJK_COMPAT_UNIT_READINGS)


